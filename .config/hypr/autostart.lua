hl.on("hyprland.start", function()
	-- Small, non-overlapping session stack. KDE services are not disabled globally.
	hl.exec_cmd("waybar")
	hl.exec_cmd("$HOME/.config/hypr/scripts/start-network-applet")
	hl.exec_cmd("$HOME/.config/hypr/scripts/start-notifications")
	hl.exec_cmd("hyprpaper")
	hl.exec_cmd("hypridle")
	hl.exec_cmd("$HOME/.config/hypr/scripts/start-polkit-agent")
	hl.exec_cmd("$HOME/.config/hypr/scripts/start-vicinae")
	hl.exec_cmd("$HOME/.config/hypr/scripts/start-swayosd")
	hl.exec_cmd("wl-paste --type text --watch cliphist store")
	hl.exec_cmd("wl-paste --type image --watch cliphist store")
	hl.exec_cmd("$HOME/.config/hypr/scripts/apply-wallpaper")
end)
